/* PACER project page — the comparison block in #idea (direction C, 2026-10-11).

   index.html carries the three cards with their final diagrams (inline SVG generated by
   _dev/tools/make_compare.py: a wide set, and a vertical set for phones). Without JS, under
   prefers-reduced-motion and in print, that final state is what shows; it reads as the
   camera-ready Fig. 1's bottom-left panels.

   With motion allowed, the sequence plays once, card 1 -> 2 -> 3, about 7.4 s in all with a short beat
   between cards, and rests on the final state: the outcome-centric card (B, C, D discarded; A, E used; six
   equal bars; Update VLA), the reward card (all traces; the French curve laid along one policy's rollout;
   Update VLA; the robot loop back into all traces; another policy's rollout that the curve does not fit),
   then PACER (all traces; both branch arrows at once; the outcome gate and the process evidence in parallel;
   both merge into chunk weights; the native loss update). Nothing returns from PACER's update. The
   pre-start state (marks hidden; regions and boxes as faint outlines, Fig. 1's plan) is applied here only.
   A card's part starts once that card itself has been reached (half of it in view, or half the viewport)
   and the part before it is done; a card below the fold is never marked seen by a card beside it (the
   two-column grid). Cards scrolled past unseen (above the viewport, or with their top above it) are skipped
   to their final state, as is a card that leaves the viewport upward unseen. The observer is disconnected
   once every card has been seen. Replay restarts the sequence from the first card in view.

   Every animated element has data-cmp (its track below) and data-k (how it moves):
   tr trace (token, start block, beads in order, slot), ar arrow (line along pathLength 1, then
   head), fd fade, pp pop, gr grow from the bottom, sl slide in from the left, rg region or box
   (outline from a faint ghost, stroke opacity data-g or 0.18, then its tint). Item i of a track's n items
   starts at t0 + spread * i / (n - 1).

   progress(track, i, n, t) and control(s, event) are pure, so both are unit-tested in node
   (_dev/tests/compare.test.js). Classic script (no modules, no fetch) so the page works from
   file://. Public API (window.PACERCompare): TRACKS, CARDS, START, CARD_END, END, ease,
   progress, init, control, limit, running; once mounted: replay(), finish(), seek(t), status().
*/
var PACERCompare = (function () {
  "use strict";

  var win = typeof window !== "undefined" ? window : null;
  var doc = win ? win.document : null;

  /* ----------------------------------------------------------- timeline */

  // [t0, duration, spread] in seconds.
  var TRACKS = {
    // 1 · outcome-centric fine-tuning (0 - 1.6 s)
    "o.rg": [0.00, 0.30, 0.10],     // the discarded and used boxes
    "o.bcd": [0.10, 0.45, 0.20],    // B, C, D: dashed grey
    "o.ae": [0.30, 0.45, 0.12],     // A, E
    "o.lbl": [0.75, 0.25, 0.08],    // discarded / used, equal weight
    "o.bars": [0.90, 0.35, 0],      // six equal bars rise together
    "o.ar": [1.15, 0.20, 0.05],
    "o.up": [1.32, 0.28, 0],        // Update VLA
    // 2 · reward-based adaptation (1.85 - 4.45 s; a beat after card 1)
    "r.rg": [1.85, 0.25, 0],        // all traces
    "r.tr": [1.90, 0.30, 0.25],     // A-E
    "r.ar1": [2.30, 0.18, 0],
    "r.fit": [2.43, 0.40, 0],       // one policy's rollout
    "r.tool": [2.65, 0.40, 0],      // the French curve slides along it and settles
    "r.plus": [2.90, 0.15, 0.20],   // + ticks on the trace
    "r.lbl": [2.95, 0.25, 0.10],    // reward / value model, fitted to this policy and task
    "r.ar2": [3.15, 0.18, 0],
    "r.up": [3.27, 0.26, 0],        // Update VLA
    "r.loop": [3.45, 0.50, 0],      // roll out on the robot, collect, repeat: back into all traces
    "r.robot": [3.65, 0.25, 0.12],
    "r.oth": [3.85, 0.35, 0],       // another policy's rollout
    "r.ghost": [4.03, 0.25, 0],     // the same curve, dashed: it does not fit
    "r.q": [4.17, 0.28, 0],
    // 3 · PACER (4.7 - 7.42 s; a beat after card 2, while the eye moves to the right-hand panel)
    "p.rg0": [4.70, 0.25, 0],       // all traces
    "p.tr": [4.75, 0.30, 0.25],     // A-E
    "p.br": [5.20, 0.35, 0],        // both branch arrows at once: process, outcome
    "p.rg1": [5.42, 0.28, 0],       // process evidence and outcome gate regions
    "p.gate": [5.55, 0.22, 0],      // outcome branch ...
    "p.pass": [5.70, 0.32, 0],      //   A, B, E pass
    "p.cd": [5.70, 0.36, 0.10],     //   C, D stop at the gate (grey)
    "p.gl": [6.05, 0.28, 0.10],     //   pass, B as partial / audit only, zero weight
    "p.ev": [5.55, 0.40, 0.18],     // ... and, in parallel, the process branch: A, B, E
    "p.st": [6.00, 0.30, 0.10],     //   chunk ticks and evidence sticks
    "p.mg": [6.35, 0.32, 0],        // both merge into
    "p.cw": [6.55, 0.22, 0],        //   process-aware chunk weights
    "p.bars": [6.62, 0.30, 0.18],   //   bars of different heights, per trace
    "p.ar": [7.02, 0.18, 0],
    "p.nl": [7.12, 0.30, 0]         // native loss update for VLA. Rest.
  };
  var CARDS = ["o", "r", "p"];
  var MAX_DT = 0.1;                 // s: a long frame gap never jumps the sequence ahead

  function r3(x) { return Math.round(x * 1000) / 1000; }
  function trackEnd(id) { var t = TRACKS[id]; return r3(t[0] + t[2] + t[1]); }
  var START = CARDS.map(function (c) {
    return Object.keys(TRACKS).filter(function (k) { return k.charAt(0) === c; })
      .reduce(function (m, k) { return Math.min(m, TRACKS[k][0]); }, Infinity);
  });
  var CARD_END = CARDS.map(function (c) {
    return Object.keys(TRACKS).filter(function (k) { return k.charAt(0) === c; })
      .reduce(function (m, k) { return Math.max(m, trackEnd(k)); }, 0);
  });
  var END = Math.max.apply(null, CARD_END);

  // Calm in-and-out (sine): ease(0) = 0, ease(1) = 1.
  function ease(u) {
    if (u <= 0) return 0;
    if (u >= 1) return 1;
    return 0.5 - 0.5 * Math.cos(Math.PI * u);
  }

  // How far item i of a track's n items has come at time t (0 .. 1).
  function progress(id, i, n, t) {
    var tr = TRACKS[id];
    if (!tr) return 1;
    var start = tr[0] + (n > 1 ? tr[2] * (i || 0) / (n - 1) : 0);
    return ease((t - start) / tr[1]);
  }

  /* -------------------------------------------------------------- player */

  function init() { return { t: 0, seen: [false, false, false], done: false, held: false, plays: 0 }; }

  // How far the sequence may run: up to the start of the first card not yet seen.
  function limit(s) {
    for (var k = 0; k < CARDS.length; k++) if (!s.seen[k]) return START[k];
    return END;
  }

  function running(s) { return !s.done && !s.held && s.t < limit(s); }

  // The pure player. Events: tick {dt}, seen {card, passed}, replay {from}, finish, seek {t}.
  function control(s, ev) {
    var n = { t: s.t, seen: s.seen.slice(), done: s.done, held: s.held, plays: s.plays };
    switch (ev.type) {
      case "tick":
        if (running(s)) {
          n.t = Math.min(limit(s), s.t + Math.min(Math.max(ev.dt || 0, 0), MAX_DT));
          if (n.t >= END) { n.t = END; n.done = true; n.plays = s.plays + 1; }
        }
        break;
      case "seen":
        // ev.card came into view (or left it upward unseen); ev.passed lists the cards scrolled past, above the
        // viewport (it may include ev.card itself). Only these are marked seen: a card below the fold waits.
        var passed = ev.passed || [];
        n.seen[ev.card] = true;
        passed.forEach(function (j) { n.seen[j] = true; });
        // the leading run of scrolled-past cards shows its final state: skip to the first card not passed
        var m = 0;
        while (m < CARDS.length && passed.indexOf(m) >= 0) m++;
        if (m > 0 && !s.done) {
          n.t = Math.max(s.t, m < CARDS.length ? START[m] : END);
          if (n.t >= END) { n.t = END; n.done = true; n.held = false; }
        }
        break;
      case "replay":
        n.t = Math.max(0, Math.min(ev.from || 0, END));
        n.seen = [true, true, true]; n.done = false; n.held = false;
        break;
      case "finish":                       // print: the final state
        n.t = END; n.done = true; n.held = false;
        break;
      case "seek":                         // tests and debugging: hold at time t
        n.t = Math.max(0, Math.min(+ev.t || 0, END)); n.held = true; n.done = false;
        break;
    }
    return n;
  }

  /* ------------------------------------------------------------ the page */

  var api = null;

  function each(list, fn) { Array.prototype.forEach.call(list, fn); }
  function clamp01(x) { return x < 0 ? 0 : x > 1 ? 1 : x; }

  function mount(root, bar) {
    if (root.__pacerCompare) return root.__pacerCompare;
    var cards = Array.prototype.slice.call(root.querySelectorAll(".compare__card"));
    var replayBtn = bar ? bar.querySelector(".compare__replay") : null;
    var motion = !(win.matchMedia && win.matchMedia("(prefers-reduced-motion: reduce)").matches);
    var anim = motion && "IntersectionObserver" in win && "requestAnimationFrame" in win;
    var s = init();
    var raf = 0, last = null, io = null;
    var styled = [];             // elements given inline styles (cleared at rest)

    // Every animated element, with its track, index and item count (per SVG: the wide and the
    // phone set both play; only one is displayed).
    var items = [];
    each(root.querySelectorAll("svg.cmp-dg"), function (svg) {
      var els = svg.querySelectorAll("[data-cmp]"), count = {};
      each(els, function (el) {
        var id = el.getAttribute("data-cmp"), i = +(el.getAttribute("data-i") || 0);
        count[id] = Math.max(count[id] || 0, i + 1);
      });
      each(els, function (el) {
        var id = el.getAttribute("data-cmp");
        var it = { el: el, id: id, i: +(el.getAttribute("data-i") || 0), n: count[id], k: el.getAttribute("data-k"), last: -1 };
        if (it.k === "rg") it.g = el.hasAttribute("data-g") ? +el.getAttribute("data-g") : 0.18;   // the ghost's stroke
        if (it.k === "tr") {
          it.tk = el.querySelectorAll(".tk");
          it.sb = el.querySelectorAll(".sb");
          it.sl = el.querySelectorAll(".sl");
          it.segs = Array.prototype.map.call(el.querySelectorAll(".sg"), function (g) {
            var ln = g.querySelector(".ln");
            return { ln: ln, dash: ln.classList.contains("dsh"), beads: g.querySelectorAll(".bd circle"), rn: g.querySelectorAll(".rn") };
          });
        } else if (it.k === "ar") {
          it.ln = el.querySelector(".ln");
          it.hd = el.querySelector(".hd");
        }
        items.push(it);
      });
    });

    function set(el, prop, value) {
      if (!el.__cmpStyled) { el.__cmpStyled = true; styled.push(el); }
      el.style[prop] = value;
    }
    function show(el, on) { set(el, "opacity", on ? "1" : "0"); }

    function apply(t) {
      items.forEach(function (it) {
        var p = progress(it.id, it.i, it.n, t);
        if (p === it.last) return;
        it.last = p;
        var el = it.el;
        switch (it.k) {
          case "tr":
            each(it.tk, function (e) { set(e, "opacity", String(clamp01(p / 0.12))); });
            each(it.sb, function (e) { show(e, p > 0); });
            var m = it.segs.length;
            it.segs.forEach(function (g, j) {
              var u = clamp01(p * m - j);
              if (g.dash) set(g.ln, "opacity", String(u));
              else { set(g.ln, "strokeDashoffset", String(1 - u)); show(g.ln, u > 0); }
              var nb = g.beads.length;
              for (var b = 0; b < nb; b++) show(g.beads[b], u > 0 && u >= (b + 0.5) / nb);
              each(g.rn, function (e) { show(e, u > 0); });
            });
            each(it.sl, function (e) { set(e, "opacity", String(clamp01((p - 0.85) / 0.15))); });
            break;
          case "ar":
            set(it.ln, "strokeDashoffset", String(1 - p));
            show(it.ln, p > 0);
            set(it.hd, "opacity", String(clamp01((p - 0.85) / 0.15)));
            break;
          case "fd":
            set(el, "opacity", String(p));
            break;
          case "pp":
            set(el, "opacity", String(p));
            set(el, "transform", p < 1 ? "scale(" + (0.82 + 0.18 * p).toFixed(4) + ")" : "");
            break;
          case "gr":
            show(el, p > 0);
            set(el, "transform", p < 1 ? "scaleY(" + p.toFixed(4) + ")" : "");
            break;
          case "sl":
            set(el, "opacity", String(p));
            set(el, "transform", p < 1 ? "translateX(" + (-14 * (1 - p)).toFixed(2) + "px)" : "");
            break;
          case "rg":
            set(el, "strokeOpacity", String(it.g + (1 - it.g) * p));
            set(el, "fillOpacity", String(p));
            break;
        }
      });
    }

    // At rest the page shows its static markup: every inline style goes.
    function rest() {
      // Chrome syncs an SVG node's style attribute lazily: empty the declaration and read the attribute (the
      // sync) before removing it, or it comes back as style="" on the next read
      styled.forEach(function (el) {
        el.style.cssText = "";
        el.getAttribute("style");
        el.removeAttribute("style");
        el.__cmpStyled = false;
      });
      styled = [];
      items.forEach(function (it) { it.last = -1; });
      root.classList.remove("cmp--play");
    }

    function render() {
      if (s.done) { rest(); return; }
      root.classList.add("cmp--play");
      apply(s.t);
    }

    function step(now) {
      raf = 0;
      if (!running(s)) { last = null; return; }
      var dt = last === null ? 0 : (now - last) / 1000;
      last = now;
      s = control(s, { type: "tick", dt: dt });
      render();
      if (running(s)) raf = win.requestAnimationFrame(step);
      else last = null;
    }

    function dispatch(ev) {
      s = control(s, ev);
      render();
      if (running(s) && !raf) { last = null; raf = win.requestAnimationFrame(step); }
    }

    // A card is reached when half of it is in view, or (a tall card) it fills half the viewport.
    var REACH = 0.5;

    // Where Replay starts: the first card well in view (as for "seen"); else the last card partly in
    // view; else, with the block above the viewport (the reader is at the Replay bar), the last card.
    function firstInView() {
      var vh = win.innerHeight || doc.documentElement.clientHeight, partly = -1, above = 0;
      for (var k = 0; k < cards.length; k++) {
        var r = cards[k].getBoundingClientRect();
        var vis = Math.min(r.bottom, vh) - Math.max(r.top, 0);
        if (vis > 0 && (vis >= REACH * r.height || vis >= 0.5 * vh)) return k;
        if (vis > 0) partly = k;
        if (r.bottom <= 0) above++;
      }
      if (partly >= 0) return partly;
      return above === cards.length ? cards.length - 1 : 0;
    }

    if (anim) {
      if (replayBtn) {
        replayBtn.hidden = false;
        replayBtn.addEventListener("click", function () { dispatch({ type: "replay", from: START[firstInView()] }); });
      }
      win.addEventListener("beforeprint", function () { dispatch({ type: "finish" }); });
      // The cards before k the reader has scrolled past: above the viewport, or (never seen) with their top
      // above it. In the two-column grid PACER sits beside the baselines, so the reward card below the fold
      // is not among them: it waits until it is reached itself.
      var passedBefore = function (k) {
        var out = [];
        for (var j = 0; j < k; j++) {
          var b = cards[j].getBoundingClientRect();
          if (b.bottom <= 0 || (b.top < 0 && !s.seen[j])) out.push(j);
        }
        return out;
      };
      io = new win.IntersectionObserver(function (entries) {
        entries.forEach(function (e) {
          var k = cards.indexOf(e.target);
          if (k < 0 || s.seen[k]) return;
          var vh = e.rootBounds ? e.rootBounds.height : win.innerHeight;
          if (e.isIntersecting) {
            if (e.intersectionRatio >= REACH || e.intersectionRect.height >= 0.5 * vh)
              dispatch({ type: "seen", card: k, passed: passedBefore(k) });
          } else if (e.boundingClientRect.bottom <= 0) {
            // left upward unseen (a fast scroll, or the page opened below it): it is scrolled past too
            dispatch({ type: "seen", card: k, passed: passedBefore(k).concat([k]) });
          }
        });
        if (s.seen.every(Boolean) && io) { io.disconnect(); io = null; }
      }, { threshold: [0, 0.1, 0.2, 0.35, 0.5, 0.75, 1] });
      cards.forEach(function (c) { io.observe(c); });
      render();                                   // the pre-start state: JS only
    }

    api = root.__pacerCompare = {
      replay: function (from) { if (anim) dispatch({ type: "replay", from: from === undefined ? START[firstInView()] : +from }); },
      finish: function () { if (anim) dispatch({ type: "finish" }); },
      seek: function (t) { if (anim) dispatch({ type: "seek", t: +t || 0 }); },
      status: function () {
        return { t: s.t, done: s.done, held: s.held, plays: s.plays, seen: s.seen.slice(), animated: anim,
                 running: anim && running(s), observing: !!io, end: END };
      }
    };
    return api;
  }

  function boot() {
    var root = doc.querySelector("#idea .compare");
    if (!root) return;
    try { mount(root, doc.querySelector("#idea .compare__bar")); } catch (err) {
      // never leave a diagram half drawn
      root.classList.remove("cmp--play");
      each(root.querySelectorAll("[style]"), function (el) { if (el.closest("svg")) el.removeAttribute("style"); });
      if (win.console) win.console.error("PACERCompare.mount failed:", err);
    }
  }

  if (doc) {
    if (doc.readyState === "loading") doc.addEventListener("DOMContentLoaded", boot);
    else boot();
  }

  function call(name) {
    return function (arg) { return api ? api[name](arg) : undefined; };
  }

  return {
    TRACKS: TRACKS,
    CARDS: CARDS,
    START: START,
    CARD_END: CARD_END,
    END: END,
    MAX_DT: MAX_DT,
    ease: ease,
    progress: progress,
    trackEnd: trackEnd,
    init: init,
    control: control,
    limit: limit,
    running: running,
    mount: mount,
    replay: call("replay"),
    finish: call("finish"),
    seek: call("seek"),
    status: call("status")
  };
})();

if (typeof window !== "undefined") window.PACERCompare = PACERCompare;
if (typeof module !== "undefined" && module.exports) module.exports = PACERCompare;
